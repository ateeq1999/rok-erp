  minimum_temperature_celsius numeric(5,2),
  maximum_temperature_celsius numeric(5,2),
  note_text text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  row_version bigint not null default 1
);
select core.prepare_table('pharmacy.receipt_quality_checks');
create index receipt_quality_checks_line_index
  on pharmacy.receipt_quality_checks (goods_receipt_line_id, created_at desc);
create index receipt_quality_checks_failed_index
  on pharmacy.receipt_quality_checks (organization_id, created_at desc) where result <> 'passed';

-- Claims are submitted to an insurer in batches, not one at a time: one period,
-- one provider, one total.
create table pharmacy.insurance_claim_batches (
  id uuid primary key default core.generate_uuid_v7(),
  organization_id uuid not null references core.organizations (id) on delete cascade,
  insurance_provider_id uuid not null references pharmacy.insurance_providers (id),
  period_start_on date not null,
  period_end_on date not null,
  status text not null default 'open'
    check (status in ('open', 'submitted', 'queried', 'paid')),
  submitted_at timestamptz,
  claimed_amount numeric(18,2) not null default 0 check (claimed_amount >= 0),
  paid_amount numeric(18,2) not null default 0 check (paid_amount >= 0),
  -- What the insurer said does not qualify.
  deducted_amount numeric(18,2) not null default 0 check (deducted_amount >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  row_version bigint not null default 1,
  check (period_end_on >= period_start_on)
);
select core.prepare_table('pharmacy.insurance_claim_batches');
create index insurance_claim_batches_provider_index
  on pharmacy.insurance_claim_batches (insurance_provider_id, period_start_on desc);

-- A claim belongs to the batch it was submitted in.
alter table pharmacy.insurance_claims
  add column claim_batch_id uuid references pharmacy.insurance_claim_batches (id) on delete set null;
create index insurance_claims_batch_index on pharmacy.insurance_claims (claim_batch_id);