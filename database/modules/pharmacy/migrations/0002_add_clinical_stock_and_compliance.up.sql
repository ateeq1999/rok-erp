-- Module: pharmacy
-- Migration 0002: the clinical, stock and compliance tables the boards need.
--
-- Migration 0001 covers the paper trail a pharmacy must keep: who prescribed
-- what, what was dispensed, the controlled substance register and insurance
-- claims. This migration covers the work around it: what a medicine is and how
-- it must be stored, what a patient's clinical record says, what the dispenser
-- checked before handing it over, and the compliance records a regulator or an
-- insurer asks for.
--
-- Conventions are the ones every module follows (see core 0001):
--   * time-ordered UUID version 7 keys, generated by the database,
--   * organization_id on every row, with row level security through prepare_table,
--   * created_at, updated_at, deleted_at and row_version,
--   * money as numeric(18,2), quantities as numeric(18,3),
--   * statuses as text with a check constraint, so a later migration can add a value.
--
-- Nothing in 0001 changes: a migration that has shipped is never edited, so this
-- file only adds.

-- One row per medicine product: what it is, how strong it is, and how it has to
-- be kept. The clinical check screen reads this to warn about a dose, a storage
-- requirement or a missing registration.
create table pharmacy.medicine_details (
  id uuid primary key default core.generate_uuid_v7(),
  organization_id uuid not null references core.organizations (id) on delete cascade,
  product_id uuid not null references catalog.products (id) on delete cascade,
  -- The regulator's own name for the strength, e.g. "500 mg" or "2 mg/ml".
  generic_name text not null,
  strength_text text not null,
  dosage_form text not null,
  -- e.g. "20 tablets", "100 ml".
  pack_size_text text,
  medicine_schedule text not null default 'general_sale'
    check (medicine_schedule in ('general_sale', 'pharmacy_medicine', 'prescription_only', 'controlled')),
  storage_condition text not null default 'room_temperature'
    check (storage_condition in ('room_temperature', 'refrigerated_two_to_eight')),
  -- Authority registration number, e.g. the Tanzania Medicines and Medical Devices Authority number.
  regulator_registration_number text,
  -- Shelf life a supplier must leave on arrival, in whole months.
  minimum_shelf_life_months_on_delivery integer not null default 0
    check (minimum_shelf_life_months_on_delivery >= 0),
  -- Printed on the label, e.g. "Keep out of reach of children".
  label_warnings text[] not null default '{}',
  is_on_insurance_formulary boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  row_version bigint not null default 1
);
select core.prepare_table('pharmacy.medicine_details');
create unique index medicine_details_product_unique_index
  on pharmacy.medicine_details (organization_id, product_id);
create index medicine_details_generic_name_index
  on pharmacy.medicine_details (organization_id, generic_name);

-- What may be given instead when the prescribed medicine is out of stock.
create table pharmacy.medicine_substitutes (
  id uuid primary key default core.generate_uuid_v7(),
  organization_id uuid not null references core.organizations (id) on delete cascade,
  product_id uuid not null references catalog.products (id) on delete cascade,
  substitute_product_id uuid not null references catalog.products (id) on delete cascade,
  substitution_kind text not null
    check (substitution_kind in ('same_generic', 'therapeutic')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  row_version bigint not null default 1,
  check (product_id <> substitute_product_id)
);
select core.prepare_table('pharmacy.medicine_substitutes');
create unique index medicine_substitutes_pair_unique_index
  on pharmacy.medicine_substitutes (organization_id, product_id, substitute_product_id);
create index medicine_substitutes_substitute_index
  on pharmacy.medicine_substitutes (substitute_product_id);

-- What the pharmacy knows about a patient beyond their name and phone number.
-- Kept apart from customers.customers so a clinical field never leaks into a
-- sale, and readable only with pharmacy.clinical_notes.view.
create table pharmacy.patient_clinical_profiles (
  id uuid primary key default core.generate_uuid_v7(),
  organization_id uuid not null references core.organizations (id) on delete cascade,
  customer_id uuid not null references customers.customers (id) on delete cascade,
  date_of_birth date,
  -- Recorded as the patient states it.
  sex text check (sex in ('female', 'male', 'other', 'unknown')),
  allergies text[] not null default '{}',
  -- Diagnoses read off prescriptions, not asserted by the pharmacist.
  conditions_from_prescriptions text[] not null default '{}',
  insurance_provider_id uuid references pharmacy.insurance_providers (id) on delete set null,
  insurance_member_number text,
  -- Whether the patient agreed to be reminded when a refill is due.
  reminder_consent boolean not null default false,
  reminder_consent_given_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  row_version bigint not null default 1
);
select core.prepare_table('pharmacy.patient_clinical_profiles');
create unique index patient_clinical_profiles_customer_unique_index
  on pharmacy.patient_clinical_profiles (organization_id, customer_id);
create index patient_clinical_profiles_insurance_index
  on pharmacy.patient_clinical_profiles (insurance_provider_id, insurance_member_number);

-- The pharmacist's own words about a patient or a prescription.
