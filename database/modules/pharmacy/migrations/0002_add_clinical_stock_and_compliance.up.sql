select core.prepare_table('pharmacy.clinical_notes');
create index clinical_notes_customer_index on pharmacy.clinical_notes (customer_id, created_at desc);
create index clinical_notes_prescription_index on pharmacy.clinical_notes (prescription_id);

-- Which two generics must not be given together, and what to say about it.
create table pharmacy.interaction_rules (
  id uuid primary key default core.generate_uuid_v7(),
  organization_id uuid not null references core.organizations (id) on delete cascade,
  first_generic_name text not null,
  second_generic_name text not null,
  severity text not null
    check (severity in ('information', 'caution', 'serious')),
  message_text text not null,
  -- Where the rule comes from, e.g. the formulary or a clinical guideline.
  source_reference text,
  -- A serious rule is not used until a pharmacist has read it.
  reviewed_by_user_id uuid references core.users (id),
  reviewed_on date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  row_version bigint not null default 1,
  check (first_generic_name <> second_generic_name)
);
select core.prepare_table('pharmacy.interaction_rules');
create unique index interaction_rules_pair_unique_index
  on pharmacy.interaction_rules (organization_id, first_generic_name, second_generic_name);
create index interaction_rules_first_index
  on pharmacy.interaction_rules (organization_id, first_generic_name);
create index interaction_rules_second_index
  on pharmacy.interaction_rules (organization_id, second_generic_name);

-- One row per check made on a prescription, so the screen can show what was
-- looked at and what the pharmacist decided.
create table pharmacy.prescription_checks (
  id uuid primary key default core.generate_uuid_v7(),
  organization_id uuid not null references core.organizations (id) on delete cascade,
  prescription_id uuid not null references pharmacy.prescriptions (id) on delete cascade,
  check_key text not null
    check (check_key in ('identity', 'allergy', 'interaction', 'duplicate_therapy', 'dose_range', 'insurance_cover')),
  result text not null check (result in ('passed', 'warning', 'failed')),
  -- What the check found, in words the pharmacist can read.
  details text,
  checked_by_user_id uuid references core.users (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  row_version bigint not null default 1
);
select core.prepare_table('pharmacy.prescription_checks');
create index prescription_checks_prescription_index
  on pharmacy.prescription_checks (prescription_id, created_at desc);
create index prescription_checks_failed_index
  on pharmacy.prescription_checks (organization_id, result) where result <> 'passed';

